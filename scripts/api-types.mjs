// Shared helpers for generating API types from docs/api/openapi.json.
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const SPEC_PATH = path.join(root, 'docs', 'api', 'openapi.json');
export const TYPES_PATH = path.join(root, 'src', 'shared', 'api', 'generated', 'schema.ts');
export const SOURCE_DIR = path.resolve(root, '..', 'charles', 'docs', 'mobile');
export const DOCS_DIR = path.join(root, 'docs', 'api');

const HEADER =
  '/* eslint-disable */\n// Generated by `pnpm sync:api` from docs/api/openapi.json. Do not edit by hand.\n\n';

export async function generateTypes() {
  const spec = JSON.parse(await readFile(SPEC_PATH, 'utf8'));
  const ast = await openapiTS(spec, { exportType: true, alphabetize: true });
  return HEADER + astToString(ast);
}

export const normalize = (text) => text.replace(/\r\n/g, '\n');
