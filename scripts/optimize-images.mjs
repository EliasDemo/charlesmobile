// pnpm images:optimize
// Reads the licensed stock photos from assets/stock/ and writes optimized WebP copies to
// assets/images/ (one width per use), then regenerates src/shared/ui/brandImages.generated.ts so the
// app can require them. Development tool only: sharp never ships inside the app.
//
// File names in assets/stock/ decide where each photo is used (see docs/licencias-imagenes.md):
//   welcome-find, welcome-book, welcome-manage   → welcome pages
//   auth-background                              → login and sign-up background
//   cover-generic, cover-<categoryKey>           → generic barbershop covers ("Imagen ilustrativa")
//   empty-bookings, empty-favorites, empty-search → empty states
import { mkdir, readdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const STOCK = path.join(root, 'assets', 'stock');
const OUT = path.join(root, 'assets', 'images');
const REGISTRY = path.join(root, 'src', 'shared', 'ui', 'brandImages.generated.ts');
const LICENSES = path.join(root, 'docs', 'licencias-imagenes.md');

/** Width per use: full-screen backgrounds need more pixels than covers or empty states. */
const WIDTH_BY_PREFIX = { 'welcome-': 1080, 'auth-': 1080, 'cover-': 720, 'empty-': 480 };
const QUALITY = 72;
const NAME = /^(welcome-(find|book|manage)|auth-background|cover-[a-z_]+|empty-(bookings|favorites|search))$/;

const kb = (bytes) => `${(bytes / 1024).toFixed(0)} KB`;

const files = (await readdir(STOCK).catch(() => [])).filter((f) => /\.(jpe?g|png|webp)$/i.test(f));
if (files.length === 0) {
  console.error('No hay fotos en assets/stock/. Cópialas ahí con los nombres de docs/licencias-imagenes.md.');
  process.exit(1);
}

const licenses = await readFile(LICENSES, 'utf8').catch(() => '');
await mkdir(OUT, { recursive: true });
const entries = [];
let before = 0;
let after = 0;

for (const file of files.sort()) {
  const key = path.parse(file).name.toLowerCase();
  if (!NAME.test(key)) {
    console.warn(`Omitida ${file}: el nombre no corresponde a ningún uso.`);
    continue;
  }
  // No license line, no photo: the app never ships an image without its documented origin.
  if (!licenses.includes(`| ${key} |`)) {
    console.warn(`Omitida ${file}: falta su fila (origen, autor y licencia) en docs/licencias-imagenes.md.`);
    continue;
  }
  const width = Object.entries(WIDTH_BY_PREFIX).find(([prefix]) => key.startsWith(prefix))?.[1] ?? 720;
  const output = path.join(OUT, `${key}.webp`);
  await sharp(path.join(STOCK, file))
    .rotate()
    .resize({ width, withoutEnlargement: true })
    .webp({ quality: QUALITY })
    .toFile(output);
  const sizeBefore = (await stat(path.join(STOCK, file))).size;
  const sizeAfter = (await stat(output)).size;
  before += sizeBefore;
  after += sizeAfter;
  entries.push(key);
  console.log(`${file}: ${kb(sizeBefore)} → ${kb(sizeAfter)} (${width} px)`);
}

const registry = `// Generated by \`pnpm images:optimize\` from assets/stock/. Do not edit by hand.
import type { ImageSourcePropType } from 'react-native';

export const brandImages: Partial<Record<string, ImageSourcePropType>> = {
${entries.map((key) => `  '${key}': require('../../../assets/images/${key}.webp'),`).join('\n')}
};
`;
await writeFile(REGISTRY, registry, 'utf8');
console.log(`\nTotal: ${kb(before)} → ${kb(after)} en ${entries.length} imágenes.`);
